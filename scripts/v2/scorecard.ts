#!/usr/bin/env tsx
/**
 * v2 scorecard (WS0): writes eval/v2/results/<date>-<branch>.md.
 *
 * Parts:
 *  A. Messy TEST set, offline and free (keyword baseline, no API key):
 *     - routing accuracy + vague-question fallback rate, on FOLLOW-UP rows only
 *     - intent field accuracy, on SEARCH rows only
 *     - does the offline app return a build when one should exist?
 *  B. Optional, PAID (--llm-intent): the same intent fields with the LLM
 *     extractor (gpt via .env.local). About USD 0.05 for ~60 rows.
 *  C. Optional (--run <dir>): simulated-user results from scripts/v2/simulate.ts.
 *
 * The LLM router behind KEYBOT_LLM_CLASSIFY is NOT measured here (WS1 will);
 * routing is the production default, the regex classifier.
 *
 * A results file is never overwritten: if one exists for today and this
 * branch, a numeric suffix is added. Commit the baseline and never edit it.
 *
 * Usage:
 *   npx tsx --tsconfig tsconfig.json scripts/v2/scorecard.ts
 *   npx tsx --tsconfig tsconfig.json scripts/v2/scorecard.ts --run eval/v2/runs/<dir>
 *   npx tsx --tsconfig tsconfig.json scripts/v2/scorecard.ts --run eval/v2/runs/<dir> --llm-intent
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

import { loadEnvFile } from "../load-env-file";

loadEnvFile();
// Keep the key aside for the optional paid pass; everything else runs offline.
const OPENAI_KEY = process.env.OPENAI_API_KEY;
delete process.env.OPENAI_API_KEY;

const { values: args } = parseArgs({
  options: {
    run: { type: "string" },
    "llm-intent": { type: "boolean", default: false },
    split: { type: "string", default: "test" },
  },
});

type IntentField = "layout" | "budgetRM" | "soundProfile" | "colour" | "useCase" | "connection";
const FIELDS: IntentField[] = ["layout", "budgetRM", "soundProfile", "colour", "useCase", "connection"];

async function main() {
  const { extractKeyboardIntent } = await import("@/lib/ai");
  const { classifyKeybotMessage } = await import("@/lib/keybot");
  const { generateRecommendationsFromMessage } = await import("@/lib/recommendations");
  const { keyboardComponents } = await import("@/data");
  const { loadMessySet, MESSY_SET_PATH } = await import("./lib/messy-set");
  const { mean, percentile, pct, ratio, stdev, fmt } = await import("./lib/stats");

  const branch = execSync("git rev-parse --abbrev-ref HEAD").toString().trim();
  const sha = execSync("git rev-parse --short HEAD").toString().trim();
  const date = new Date().toISOString().slice(0, 10);
  const out: string[] = [
    `# v2 scorecard: ${date} · \`${branch}\` @ ${sha}`,
    "",
    `Generated by \`scripts/v2/scorecard.ts\`. Do not edit by hand; re-run the script for new numbers (new file).`,
    "",
  ];

  // ── A. Messy set, offline ──────────────────────────────────────────────────
  if (!existsSync(MESSY_SET_PATH)) {
    out.push("## A. Messy test set", "", `_Skipped: ${MESSY_SET_PATH} does not exist yet._`, "");
  } else {
    const rows = loadMessySet().filter((r) => r.split === args.split);
    const followups = rows.filter((r) => r.entryPoint === "followup");
    const searches = rows.filter((r) => r.entryPoint === "search");

    // Routing (follow-up rows).
    let routeOk = 0, vague = 0;
    const confusions = new Map<string, number>();
    for (const r of followups) {
      const got = classifyKeybotMessage(r.text);
      if (got === r.expectedRoute) routeOk++;
      else confusions.set(`${r.expectedRoute} → ${got}`, (confusions.get(`${r.expectedRoute} → ${got}`) ?? 0) + 1);
      if (got === "vague_question" && r.expectedRoute !== "vague_question") vague++;
    }

    // Intent (search rows).
    type FieldTally = Record<IntentField, { ok: number; n: number }>;
    const newTally = (): FieldTally =>
      Object.fromEntries(FIELDS.map((f) => [f, { ok: 0, n: 0 }])) as FieldTally;

    async function scoreIntent(useLlm: boolean) {
      const tally = newTally();
      let rowsAllOk = 0;
      if (useLlm) process.env.OPENAI_API_KEY = OPENAI_KEY;
      try {
        for (const r of searches) {
          const { intent } = await extractKeyboardIntent({ message: r.text });
          const e = r.expectedIntent!;
          const actual: Record<IntentField, unknown> = {
            layout: intent.layout,
            budgetRM: intent.budget?.amount ?? null,
            soundProfile: intent.soundProfile,
            colour: intent.colour && intent.colour.length ? [...intent.colour].sort() : null,
            useCase: intent.useCase,
            // The intent schema has no connection field; "wireless" in
            // priorities is the closest signal the app has.
            connection: intent.priorities.includes("wireless") ? "wireless" : null,
          };
          const expected: Record<IntentField, unknown> = {
            ...e,
            colour: e.colour && e.colour.length ? [...e.colour].sort() : null,
            // A wired request is not representable either; score it as "no signal".
            connection: e.connection === "wireless" ? "wireless" : null,
          };
          let allOk = true;
          for (const f of FIELDS) {
            tally[f].n++;
            if (JSON.stringify(actual[f]) === JSON.stringify(expected[f])) tally[f].ok++;
            else allOk = false;
          }
          if (allOk) rowsAllOk++;
        }
      } finally {
        delete process.env.OPENAI_API_KEY;
      }
      const ok = FIELDS.reduce((s, f) => s + tally[f].ok, 0);
      const n = FIELDS.reduce((s, f) => s + tally[f].n, 0);
      return { tally, overall: ratio(ok, n), rowsAllOk };
    }

    const kw = await scoreIntent(false);
    const llm = args["llm-intent"] && OPENAI_KEY ? await scoreIntent(true) : null;

    // Build coverage (search rows, offline app).
    let shouldExist = 0, found = 0, shouldNot = 0, falseBuild = 0;
    for (const r of searches) {
      if (r.buildShouldExist === null) continue;
      const result = await generateRecommendationsFromMessage(
        { message: r.text },
        { catalogComponents: keyboardComponents },
      );
      const has = result.recommendations.length > 0;
      if (r.buildShouldExist) { shouldExist++; if (has) found++; }
      else { shouldNot++; if (has) falseBuild++; }
    }

    out.push(
      `## A. Messy set (${args.split.toUpperCase()} split, ${rows.length} rows: ${searches.length} search, ${followups.length} follow-up)`,
      "",
      "| metric | rows | keyword baseline (offline)" + (llm ? " | LLM extractor" : "") + " |",
      "|---|---|---" + (llm ? "|---" : "") + "|",
      `| routing accuracy (follow-up rows) | ${followups.length} | ${pct(ratio(routeOk, followups.length))}` + (llm ? " | (not measured; WS1)" : "") + " |",
      `| falls back to vague_question (follow-up rows) | ${followups.length} | ${pct(ratio(vague, followups.length))}` + (llm ? " | (not measured; WS1)" : "") + " |",
      `| intent field accuracy, all fields (search rows) | ${searches.length} | ${pct(kw.overall)}` + (llm ? ` | ${pct(llm.overall)}` : "") + " |",
      ...FIELDS.map(
        (f) =>
          `| &nbsp;&nbsp;${f}${f === "connection" ? " (proxy: priorities.wireless)" : ""} | ${kw.tally[f].n} | ${pct(ratio(kw.tally[f].ok, kw.tally[f].n))}` +
          (llm ? ` | ${pct(ratio(llm.tally[f].ok, llm.tally[f].n))}` : "") + " |",
      ),
      `| search rows with every field right | ${searches.length} | ${pct(ratio(kw.rowsAllOk, searches.length))}` + (llm ? ` | ${pct(ratio(llm.rowsAllOk, searches.length))}` : "") + " |",
      `| build returned when one should exist | ${shouldExist} | ${pct(ratio(found, shouldExist))}` + (llm ? " | — |" : " |"),
      `| build returned when none should exist | ${shouldNot} | ${pct(ratio(falseBuild, shouldNot))}` + (llm ? " | — |" : " |"),
      "",
      "Routing = production default (regex `classifyKeybotMessage`). The LLM router behind `KEYBOT_LLM_CLASSIFY` exists but is off by default and is not measured here (WS1).",
      "",
    );
    if (confusions.size > 0) {
      out.push(
        "<details><summary>Routing confusions (expected → got)</summary>",
        "",
        ...[...confusions.entries()].sort((a, b) => b[1] - a[1]).map(([k, v]) => `- ${k}: ${v}`),
        "",
        "</details>",
        "",
      );
    }
  }

  // ── C. Simulated users ─────────────────────────────────────────────────────
  if (args.run) {
    type S = import("./simulate").SessionRecord;
    const sessions = readFileSync(join(args.run, "sessions.jsonl"), "utf8")
      .split(/\r?\n/).filter(Boolean).map((l) => JSON.parse(l) as S);
    const judged = sessions.filter((s) => s.verdict);
    const runsPerPersona = Math.max(...sessions.map((s) => s.run));

    const successRate = (list: S[], withCode: boolean) =>
      ratio(list.filter((s) => s.verdict!.success && (!withCode || s.hardRequirements.pass)).length, list.length);

    // Spread: success rate of each repeat run (run 1, run 2, ...).
    const perRun = [...new Set(judged.map((s) => s.run))].map((r) =>
      successRate(judged.filter((s) => s.run === r), false)!,
    );
    const spread = runsPerPersona < 2 ? "1 run, spread unknown" : `±${pct(stdev(perRun))} (sd across ${runsPerPersona} runs)`;

    const turnsOk = judged.filter((s) => s.verdict!.success && s.verdict!.turnsToSuccess !== null).map((s) => s.verdict!.turnsToSuccess!);
    const callMs = sessions.flatMap((s) => s.turns.flatMap((t) => t.calls.map((c) => c.ms)));
    const turnMs = sessions.flatMap((s) => s.turns.filter((t) => t.calls.length).map((t) => t.calls.reduce((a, c) => a + c.ms, 0)));
    const hardIds = sessions.flatMap((s) => s.invented.unknownIds);
    const possible = sessions.flatMap((s) => s.invented.possible.map((p) => ({ ...p, key: `${s.personaId}-run${s.run}` })));
    const honestyCases = judged.filter((s) => s.verdict!.honesty !== "not_applicable");
    const cost = sessions.map((s) => s.costUSD.persona + s.costUSD.judge + s.costUSD.appEstimate);
    const measured = sessions.map((s) => s.costUSD.persona + s.costUSD.judge);
    const fallbackSessions = sessions.filter((s) => s.appSources.some((x) => x.startsWith("fallback")));

    out.push(
      `## C. Simulated users (\`${args.run}\`)`,
      "",
      `${new Set(sessions.map((s) => s.personaId)).size} personas × ${runsPerPersona} run(s) = ${sessions.length} sessions (${judged.length} judged). Rubric ${judged[0]?.rubricVersion ?? "?"}.`,
      "",
      "| metric | value |",
      "|---|---|",
      `| task success (judge) | ${pct(successRate(judged, false))} · ${spread} |`,
      `| task success (judge AND code check of hard requirements) | ${pct(successRate(judged, true))} |`,
      `| turns to an accepted build (successful sessions, mean / p50) | ${fmt(mean(turnsOk), 1)} / ${fmt(percentile(turnsOk, 50))} |`,
      `| confusion, mean (1 clear … 5 unusable) | ${fmt(mean(judged.map((s) => s.verdict!.confusion)), 2)} |`,
      `| **invented parts: unknown component IDs (hard fail)** | **${hardIds.length}** |`,
      `| invented parts: possible text flags (hand review) | ${possible.length} |`,
      `| honesty where something unavailable was asked | ${pct(ratio(honestyCases.filter((s) => s.verdict!.honesty === "honest").length, honestyCases.length))} (${honestyCases.length} sessions) |`,
      `| reply time per app call, p50 / p95 | ${fmt(percentile(callMs, 50), 0, " ms")} / ${fmt(percentile(callMs, 95), 0, " ms")} (${callMs.length} calls) |`,
      `| reply time per turn (all calls in the turn), p50 / p95 | ${fmt(percentile(turnMs, 50), 0, " ms")} / ${fmt(percentile(turnMs, 95), 0, " ms")} |`,
      `| cost per session, mean (persona + judge measured, app estimated) | USD ${fmt(mean(cost), 4)} (measured part ${fmt(mean(measured), 4)}) |`,
      `| sessions where the app used a fallback (no AI) | ${fallbackSessions.length} |`,
      "",
      "### Per persona",
      "",
      "| persona | runs | judge success | code check | turns | confusion | ended |",
      "|---|---|---|---|---|---|---|",
      ...[...new Set(sessions.map((s) => s.personaId))].map((id) => {
        const list = sessions.filter((s) => s.personaId === id);
        const j = list.filter((s) => s.verdict);
        return `| ${id} | ${list.length} | ${j.filter((s) => s.verdict!.success).length}/${j.length} | ${list.filter((s) => s.hardRequirements.pass).length}/${list.length} | ${list.map((s) => s.turns.length).join(", ")} | ${j.map((s) => s.verdict!.confusion).join(", ")} | ${list.map((s) => s.endedWith).join(", ")} |`;
      }),
      "",
    );
    if (hardIds.length) out.push("**Unknown IDs:** " + [...new Set(hardIds)].map((i) => `\`${i}\``).join(", "), "");
    if (possible.length) {
      out.push(
        "<details><summary>Possible invented-part flags (for HQ to review by hand)</summary>",
        "",
        "| session | turn | term | reason | echoed from user |",
        "|---|---|---|---|---|",
        ...possible.map((p) => `| ${p.key} | ${p.turn} | ${p.term} | ${p.reason} | ${p.echoedFromUser ? "yes" : "no"} |`),
        "",
        "</details>",
        "",
      );
    }
  }

  mkdirSync(join("eval", "v2", "results"), { recursive: true });
  let path = join("eval", "v2", "results", `${date}-${branch.replace(/\//g, "-")}.md`);
  for (let i = 2; existsSync(path); i++) {
    path = join("eval", "v2", "results", `${date}-${branch.replace(/\//g, "-")}-${i}.md`);
  }
  writeFileSync(path, out.join("\n") + "\n");
  console.log(out.join("\n"));
  console.log(`\nWrote ${path}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
